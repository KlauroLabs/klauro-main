pub fn spec_for(id: &str) -> Option<&'static LanguageSpec> {
    let id = match id {
        "shell" | "fish" => "bash",
        "terraform" => "hcl",
        "cuda" => "cpp",
        "luau" => "lua",
        "hack" => "php",
        "purescript" => "haskell",
        other => other,
    };
    SPECS.iter().find(|spec| spec.id == id)
}

