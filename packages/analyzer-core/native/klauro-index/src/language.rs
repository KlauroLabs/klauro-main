use tree_sitter::Language;

use crate::model::NodeKind;

pub struct Declares {
    pub type_kinds: &'static [(&'static str, NodeKind)],
    pub function_kinds: &'static [(&'static str, NodeKind)],
    pub field_kinds: &'static [&'static str],
    pub import_kinds: &'static [&'static str],
    pub constructor_kinds: &'static [&'static str],
    pub impl_kinds: &'static [&'static str],
    pub impl_type_field: &'static str,
    pub heritage_kinds: &'static [&'static str],
    pub lambda_kinds: &'static [&'static str],
    pub binding_kinds: &'static [&'static str],
    pub binding_name_field: &'static str,
    pub binding_type_field: &'static str,
    pub binding_value_field: &'static str,
    pub decorator_kinds: &'static [&'static str],
    pub decorator_container_kinds: &'static [&'static str],
    pub type_requires_body: bool,
    pub text_kinds: &'static [&'static str],
}

pub struct Names {
    pub fields: &'static [&'static str],
    pub descend: &'static [&'static str],
    pub leaf_kinds: &'static [&'static str],
    pub whole_kinds: &'static [&'static str],
    pub skip_words: &'static [&'static str],
    pub require_field: bool,
}

pub struct Signature {
    pub parameter_fields: &'static [&'static str],
    pub parameter_kinds: &'static [&'static str],
    pub parameter_type_kinds: &'static [&'static str],
    pub return_fields: &'static [&'static str],
    pub return_child_kinds: &'static [&'static str],
    pub body_fields: &'static [&'static str],
    pub constructor_parameter_path: &'static [&'static str],
    pub extension_receiver_kinds: &'static [&'static str],
}

pub struct Calls {
    pub kinds: &'static [&'static str],
    pub receiver_fields: &'static [&'static str],
    pub call_receiver_fields: &'static [&'static str],
    pub receiver_type_field: &'static str,
}

pub struct Flow {
    pub branch_kinds: &'static [&'static str],
    pub loop_kinds: &'static [&'static str],
    pub return_kinds: &'static [&'static str],
    pub throw_kinds: &'static [&'static str],
    pub await_kinds: &'static [&'static str],
}

pub struct Keywords {
    pub kind: &'static str,
    pub target_field: &'static str,
    pub types: &'static [&'static str],
    pub functions: &'static [&'static str],
}

pub struct LanguageSpec {
    pub id: &'static str,
    pub declares: Declares,
    pub names: Names,
    pub signature: Signature,
    pub calls: Calls,
    pub flow: Flow,
    pub keywords: Keywords,
}

